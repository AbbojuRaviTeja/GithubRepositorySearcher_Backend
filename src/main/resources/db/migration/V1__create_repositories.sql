CREATE TABLE repositories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    github_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    full_name VARCHAR(512),
    description VARCHAR(4000),
    owner VARCHAR(255),
    language VARCHAR(255),
    stars BIGINT NOT NULL DEFAULT 0,
    forks BIGINT NOT NULL DEFAULT 0,
    last_updated TIMESTAMP(6) WITH TIME ZONE,
    html_url VARCHAR(2048),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_repositories_github_id UNIQUE (github_id)
);

CREATE INDEX idx_repositories_language_lower ON repositories (LOWER(language));
CREATE INDEX idx_repositories_stars ON repositories (stars);
CREATE INDEX idx_repositories_forks ON repositories (forks);
CREATE INDEX idx_repositories_last_updated ON repositories (last_updated);
